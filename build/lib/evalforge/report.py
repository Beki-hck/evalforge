def html_report(runs: list[dict], title: str = "evalforge report") -> str:
    e = html.escape
    cards = "".join(
        f'<div class="card"><span>{e(r["model"])} · {e(r["suite"])}</span><b>{_pct(r["accuracy"])}</b>'
        f'<span>{r["passed"]}/{r["n"]} passed · {r.get("errors", 0)} errors · median {r.get("median_latency_s") or "–"}s</span>'
        f'<div class="bar"><i style="width:{r["accuracy"] * 100:.1f}%"></i></div></div>'
        for r in runs
    )
    cats = sorted({c for r in runs for c in r["by_category"]})
    cat_rows = "".join(
        f"<tr><td>{e(c)}</td>" + "".join(
            f"<td>{_pct(r['by_category'][c]['accuracy'])}</td>" if c in r["by_category"] else "<td>–</td>" for r in runs
        ) + "</tr>"
        for c in cats
    )
    cat_head = "".join(f"<th>{e(r['model'])}</th>" for r in runs)

    detail = []
    for r in runs:
        rows = "".join(
            f'<tr><td>{e(x["id"])}</td><td class="{"ok" if x["passed"] else "bad"}">{"pass" if x["passed"] else "fail"}</td>'
            f'<td>{e(x["detail"] or "")}{"<br><small class=bad>" + e(x["error"]) + "</small>" if x.get("error") else ""}</td>'
            f'<td><details><summary>show</summary><b>Prompt</b><pre>{e(x["prompt"])}</pre><b>Answer</b><pre>{e(x["answer"])}</pre></details></td></tr>'
            for x in r["results"]
        )
        detail.append(
            f'<h3>{e(r["model"])} · {e(r["suite"])}</h3><div class="wrap"><table><tr><th>Item</th><th>Result</th><th>Why</th><th>Transcript</th></tr>{rows}</table></div>'
        )

    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(title)}</title><style>{_CSS}</style></head><body><main>
<h1>{e(title)}</h1><p class="sub">{len(runs)} run(s) · generated by evalforge</p>
<div class="cards">{cards}</div>
<h2>Accuracy by category</h2><div class="wrap"><table><tr><th>Category</th>{cat_head}</tr>{cat_rows}</table></div>
<h2>Every item</h2>{''.join(detail)}
</main></body></html>"""
