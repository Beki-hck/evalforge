"""Turns saved run results into a Markdown table or a standalone HTML report."""

from __future__ import annotations

import html
import json
from pathlib import Path


def load_runs(paths: list[str | Path]) -> list[dict]:
    return [json.loads(Path(p).read_text(encoding="utf-8")) for p in paths]


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def markdown_table(runs: list[dict]) -> str:
    cats = sorted({c for r in runs for c in r["by_category"]})
    head = "| Model | Suite | Overall | " + " | ".join(cats) + " |"
    sep = "|" + "---|" * (3 + len(cats))
    rows = []
    for r in sorted(runs, key=lambda r: (r["suite"], -r["accuracy"])):
        cells = [_pct(r["by_category"][c]["accuracy"]) if c in r["by_category"] else "–" for c in cats]
        rows.append(f"| {r['model']} | {r['suite']} | **{_pct(r['accuracy'])}** ({r['passed']}/{r['n']}) | " + " | ".join(cells) + " |")
    return "\n".join([head, sep, *rows])


